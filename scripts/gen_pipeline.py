#!/usr/bin/env python3
"""Generate a relay pipeline: spec JSON + launch file + roshanavi projects (pure Python, no ROS).

  scripts/gen_pipeline.py --preset medium                 # -> examples/pipeline_medium/
  scripts/gen_pipeline.py --shape fanout --stages 5 --width 3 --rate 50 --process-ms 2 --out /tmp/p
  scripts/gen_pipeline.py --all                           # the three presets in examples/

Presets: small (3-stage chain), medium (5 x 4 grid = 20 nodes), large (10 x 20 grid = 200 nodes).
Output directory: pipeline.json, pipeline.launch.py, roshanavi.yaml (one process per node),
roshanavi_container.yaml (everything in a composable container). Formats and the meaning of all
options: docs/design/nodes.md ("中継パイプライン").
"""
import argparse
import os
import sys
from typing import List, Optional

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, 'ros2_ws', 'src', 'roshanavi_examples'))

from roshanavi_examples import pipeline_gen as gen  # noqa: E402

# Where the roshanavi server sees the generated files (docker compose mounts examples/ there).
SERVER_EXAMPLES_DIR = '/examples'


def parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument('--preset', choices=list(gen.PRESETS), help='size preset')
    ap.add_argument('--all', action='store_true', help='all presets into examples/pipeline_<preset>/')
    ap.add_argument('--shape', choices=gen.SHAPES)
    ap.add_argument('--stages', type=int)
    ap.add_argument('--width', type=int)
    ap.add_argument('--links', choices=gen.LINKS, help='grid: straight columns or a mesh')
    ap.add_argument('--rate', type=float, dest='rate_hz', help='Hz per source')
    ap.add_argument('--payload-bytes', type=int, dest='payload_bytes')
    ap.add_argument('--process-ms', type=float, dest='process_ms', help='time per message per relay')
    ap.add_argument('--process-mode', choices=gen.PROCESS_MODES, dest='process_mode')
    ap.add_argument('--relay-payload-bytes', type=int, dest='relay_payload_bytes',
                    help='size relays create (-1: pass the input through)')
    ap.add_argument('--rate-limit', type=float, dest='rate_limit_hz', help='Hz cap per relay')
    ap.add_argument('--drop-ratio', type=float, dest='drop_ratio')
    ap.add_argument('--no-keep-stamp', action='store_false', dest='keep_stamp', default=None)
    ap.add_argument('--topic-prefix', dest='topic_prefix')
    ap.add_argument('--mode', choices=gen.MODES, help='default mode of the launch file')
    ap.add_argument('--containers', type=int, help='number of containers (container mode)')
    ap.add_argument('--container-type', choices=gen.CONTAINER_TYPES, dest='container_type')
    ap.add_argument('--intra-process', action='store_true', default=None, dest='intra_process')
    ap.add_argument('--name', help='pipeline / directory name (default pipeline_<preset|shape>)')
    ap.add_argument('--out', help='output directory (default examples/<name>)')
    ap.add_argument('--server-dir', help='where the roshanavi server sees the output directory '
                    f'(default {SERVER_EXAMPLES_DIR}/<name> for examples/, else the output path)')
    return ap.parse_args(argv)


def params_from(args: argparse.Namespace, preset: Optional[str]) -> gen.PipelineParams:
    overrides = {k: v for k, v in vars(args).items()
                 if v is not None and k in gen.PipelineParams.__dataclass_fields__}
    if preset:
        return gen.preset_params(preset, **overrides)
    return gen.PipelineParams(**overrides)


def write_pipeline(pipe: gen.Pipeline, out_dir: str, server_dir: str) -> List[str]:
    os.makedirs(out_dir, exist_ok=True)
    spec_path = f'{server_dir}/pipeline.json'
    files = {
        'pipeline.json': gen.spec_json(pipe),
        'pipeline.launch.py': gen.launch_file_text(pipe),
        'roshanavi.yaml': gen.project_yaml(
            pipe, spec_path, 'process',
            f'{gen.describe(pipe)}\nGenerated by scripts/gen_pipeline.py; one process per node.'),
        'roshanavi_container.yaml': gen.project_yaml(
            pipe, spec_path, 'container',
            f'{gen.describe(pipe)}\nGenerated by scripts/gen_pipeline.py; composable container.'),
    }
    for name, text in files.items():
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8') as fh:
            fh.write(text)
    return sorted(files)


def generate(args: argparse.Namespace, preset: Optional[str]) -> None:
    pipe_params = params_from(args, preset)
    name = args.name or f'pipeline_{preset or pipe_params.shape}'
    pipe = gen.build_pipeline(pipe_params, name)
    out_dir = args.out or os.path.join(REPO, 'examples', name)
    in_examples = os.path.abspath(out_dir) == os.path.join(REPO, 'examples', name)
    server_dir = args.server_dir or (f'{SERVER_EXAMPLES_DIR}/{name}' if in_examples
                                     else os.path.abspath(out_dir))
    files = write_pipeline(pipe, out_dir, server_dir)
    print(gen.describe(pipe))
    print(f'  wrote {", ".join(files)} to {out_dir}')


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    try:
        if args.all:
            for preset in gen.PRESETS:
                generate(argparse.Namespace(**{**vars(args), 'name': None, 'out': None}), preset)
        else:
            if not args.preset and not args.shape:
                print('give --preset, --all or --shape', file=sys.stderr)
                return 2
            generate(args, args.preset)
    except ValueError as exc:
        print(f'error: {exc}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
