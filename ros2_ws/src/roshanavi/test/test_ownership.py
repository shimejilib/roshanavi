"""Files roshanavi creates in the workspace belong to the folder's owner (docs/design/user-code.md).

The server runs as root in Docker while ``/ws/src`` is a folder of the host user. Real ``chown``
needs root (the test container is root; elsewhere those tests skip); the rest fakes ``geteuid`` and
records ``lchown`` calls, so the rules are checked everywhere: only paths this call created, never
a symlink's target, nothing when not root or when the folder is root's own.
"""

import os

import pytest

from roshanavi import ownership
from roshanavi.function import scaffold
from roshanavi.function.codegen import write_source
from roshanavi.function.scopes import CodeLocations
from roshanavi.launcher.dummy_config import write_atomic

IS_ROOT = os.geteuid() == 0
needs_root = pytest.mark.skipif(not IS_ROOT, reason='chown to another user needs root')
USER = (4242, 4343)
SOURCE_1 = '# Generated by roshanavi from a test\nx = 1\n'
SOURCE_2 = SOURCE_1.replace('1', '2')


@pytest.fixture
def calls(monkeypatch):
    """Record ``lchown`` instead of doing it, and pretend to be root."""
    recorded = []
    monkeypatch.setattr(os, 'geteuid', lambda: 0)
    monkeypatch.setattr(os, 'lchown', lambda path, uid, gid: recorded.append((path, uid, gid)))
    return recorded


@pytest.fixture
def src(tmp_path):
    path = tmp_path / 'ws' / 'src'
    path.mkdir(parents=True)
    if IS_ROOT:
        os.chown(path, *USER)       # the host user's folder (not root's own: that changes nothing)
    return path


def test_owner_is_the_nearest_existing_directory(src, calls):
    info = os.stat(src)
    assert ownership.owner_for(str(src / 'new' / 'deeper')) == (info.st_uid, info.st_gid)


@needs_root
def test_roots_own_folder_changes_nothing(tmp_path, calls):
    assert ownership.owner_for(str(tmp_path)) is None


def test_not_root_does_nothing(src, monkeypatch):
    done = []
    monkeypatch.setattr(os, 'geteuid', lambda: 1000)
    monkeypatch.setattr(os, 'lchown', lambda *a: done.append(a))
    assert ownership.owner_for(str(src)) is None
    ownership.give_to([str(src)], None)
    scaffold.scaffold(CodeLocations.of(str(src.parent)), 'plain_user')
    assert done == []


def test_scaffold_gives_only_what_it_created(src, calls):
    existing = src / 'theirs'
    existing.mkdir()
    (existing / 'keep.py').write_text('x = 1\n')
    result = scaffold.scaffold(CodeLocations.of(str(src.parent)), 'my_logic')
    info = os.stat(src)
    changed = {path for path, uid, gid in calls}
    assert all((uid, gid) == (info.st_uid, info.st_gid) for _, uid, gid in calls)
    assert str(src / 'my_logic') in changed and result['files'][0] in changed
    assert len(changed) == 1 + 3 + len(result['files'])     # dir, resource / my_logic / test, files
    assert not [p for p in changed if str(existing) in p or p == str(src)]


def test_symlink_is_not_followed(src, tmp_path, calls):
    """A path that turned into a symlink: ``lchown`` changes the link, never the target."""
    outside = tmp_path / 'outside.txt'
    outside.write_text('x')
    link = src / 'link'
    link.symlink_to(outside)
    ownership.give_to([str(link)], USER)
    assert calls == [(str(link), *USER)]        # lchown (not chown) was the call used
    assert outside.read_text() == 'x'


def test_failure_is_logged_not_raised(src, monkeypatch):
    def refuse(path, uid, gid):
        raise PermissionError(1, 'Operation not permitted')
    warnings = []
    monkeypatch.setattr(os, 'lchown', refuse)
    monkeypatch.setattr(ownership.LOG, 'warning', lambda *args: warnings.append(args))
    ownership.give_to([str(src)], USER)
    assert len(warnings) == 1 and 'root-owned' in warnings[0][0]


def test_makedirs_owned_lists_only_missing_directories(src, calls):
    (src / 'a').mkdir()
    if IS_ROOT:
        os.chown(src / 'a', *USER)
    ownership.makedirs_owned(str(src / 'a' / 'b' / 'c'))
    assert {p for p, _, _ in calls} == {str(src / 'a' / 'b'), str(src / 'a' / 'b' / 'c')}


def test_write_atomic_and_export_code_use_the_owner(src, calls):
    write_source(str(src / 'out'), 'n_node.py', SOURCE_1)
    assert str(src / 'out') in {p for p, _, _ in calls}
    assert any(os.path.basename(p).startswith('.roshanavi-') for p, _, _ in calls)  # temp file
    calls.clear()
    write_atomic(str(src / 'plain.txt'), 'x')                # no owner given: untouched
    assert calls == []


@needs_root
def test_scaffold_real_chown_to_the_owner_of_src(src):
    os.chown(src, *USER)
    existing = src / 'theirs'
    existing.mkdir()
    (existing / 'keep.py').write_text('x = 1\n')
    result = scaffold.scaffold(CodeLocations.of(str(src.parent)), 'my_logic')
    created = [result['directory'], *result['files']]
    created += [os.path.join(result['directory'], d) for d in ('my_logic', 'resource', 'test')]
    for path in created:
        info = os.lstat(path)
        assert (info.st_uid, info.st_gid) == USER, path
    assert os.lstat(existing).st_uid == 0 and os.lstat(existing / 'keep.py').st_uid == 0


@needs_root
def test_export_code_real_chown_and_replaced_file(src):
    os.chown(src, *USER)
    result = write_source(str(src / 'new_dir'), 'n_node.py', SOURCE_1)
    assert os.lstat(src / 'new_dir').st_uid == USER[0]
    assert os.lstat(result['file']).st_gid == USER[1]
    write_source(str(src / 'new_dir'), 'n_node.py', SOURCE_2)
    assert os.lstat(result['file']).st_uid == USER[0]


@needs_root
def test_symlink_target_untouched_with_a_real_chown(src, tmp_path):
    outside = tmp_path / 'outside.txt'
    outside.write_text('x')
    link = src / 'link'
    link.symlink_to(outside)
    ownership.give_to([str(link)], USER)
    assert os.lstat(link).st_uid == USER[0]
    assert os.stat(outside).st_uid == 0


def test_exported_code_is_readable_by_others(tmp_path):
    out = write_source(str(tmp_path / 'exported'), 'node.py', SOURCE_1)
    assert os.stat(out['file']).st_mode & 0o777 == 0o644


def test_write_atomic_keeps_0600_by_default(tmp_path):
    path = tmp_path / 'state.json'
    write_atomic(str(path), '{}')
    assert os.stat(path).st_mode & 0o777 == 0o600
