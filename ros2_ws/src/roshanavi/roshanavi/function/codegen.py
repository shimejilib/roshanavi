"""「ROS ノードのコードとして書き出す」: a function node as a standalone, commented rclpy node.

The generated file does what the function node does, without roshanavi: it is
both the way out ("graduation") and a lesson in how the function was wrapped.
Every value embedded in the source is validated by the schema and written with
``repr()``; the output directory is checked by the caller (workspace containment,
no control characters).
"""

import os
from typing import Dict, List, Optional, Tuple

from ..launcher import command
from ..launcher.dummy_config import has_control_chars, write_atomic
from ..launcher.errors import LauncherError
from ..launcher.schema import FunctionSpec
from .core import Port, resolve_ports
from .modules import list_functions, resolve_module

MARKER_PREFIX = '# Generated by roshanavi from '   # also on class nodes' files (class_codegen)
MARKER = MARKER_PREFIX + 'function node'

_SCALAR_IN = {
    'string': ('msg.data', '文字列: the text in the message\'s data field (str)'),
    'float': ('float(msg.data)', '数値 (小数): the data field as a float'),
    'int': ('int(msg.data)', '整数: the data field as an int'),
    'bool': ('bool(msg.data)', 'ON / OFF: the data field as a bool'),
    'numbers': ('[float(x) for x in msg.data]', '数値の並び: the data array as a list'),
    'json': ('json.loads(msg.data)', 'JSON: the text in data, parsed (dict / list ...)'),
    'bytes': ('bytes(msg.data)', 'バイト列: the data array as bytes'),
    'image': ('image_to_array(msg)', '画像: H x W x 3 RGB (or H x W gray) numpy array'),
    'message': ('message_to_ordereddict(msg)', '専用の型: the whole message as a dict'),
}

HELPERS_IMAGE = '''

def image_to_array(msg):
    """sensor_msgs/Image -> numpy array (rgb8 / bgr8 -> H x W x 3 RGB, mono8 -> H x W)."""
    channels = 1 if msg.encoding == 'mono8' else 3
    rows = np.frombuffer(bytes(msg.data), dtype=np.uint8).reshape(msg.height, msg.step)
    pixels = rows[:, :msg.width * channels].reshape(msg.height, msg.width, channels)
    if msg.encoding == 'bgr8':
        pixels = pixels[:, :, ::-1]
    return pixels[:, :, 0].copy() if channels == 1 else pixels.copy()


def array_to_image(value, out, stamp):
    """numpy uint8 array (H x W x 3 RGB or H x W gray) -> fields of sensor_msgs/Image."""
    value = np.ascontiguousarray(value, dtype=np.uint8)
    out.header.stamp = stamp
    out.height, out.width = value.shape[:2]
    out.encoding = 'mono8' if value.ndim == 2 else 'rgb8'
    out.step = out.width * (1 if value.ndim == 2 else 3)
    out.data = value.tobytes()
    return out
'''


def class_names(types: List[str]) -> Dict[str, Tuple[str, str]]:
    """type -> (import line, local name); the package is added when two names clash."""
    names: Dict[str, Tuple[str, str]] = {}
    short = [t.split('/')[-1] for t in types]
    for type_name in types:
        pkg, name = type_name.split('/')[0], type_name.split('/')[-1]
        local = f'{pkg}_{name}' if short.count(name) > 1 else name
        alias = f' as {local}' if local != name else ''
        names[type_name] = (f'from {pkg}.msg import {name}{alias}', local)
    return names


def input_expr(port: Port) -> Tuple[str, str]:
    if port.kind == 'audio':
        if port.type.endswith('/AudioDataStamped'):
            return "np.frombuffer(bytes(msg.audio.data), dtype='<i2')", '音声: int16 samples'
        if port.type.endswith('/AudioData'):
            return "np.frombuffer(bytes(msg.data), dtype='<i2')", '音声: int16 samples'
        return 'np.array(msg.data, dtype=np.int16)', '音声: int16 samples'
    if port.kind == 'numbers' and 'Float' not in port.type:
        return '[int(x) for x in msg.data]', '数値の並び: the data array as a list'
    return _SCALAR_IN[port.kind]


def output_lines(port: Port, cls: str) -> List[str]:
    """Statements turning ``result`` into ``out`` (indented by the caller)."""
    lines = [f'out = {cls}()']
    kind = port.kind
    if kind in ('string', 'float', 'int', 'bool'):
        conv = {'string': 'str', 'float': 'float', 'int': 'int', 'bool': 'bool'}[kind]
        lines.append(f'out.data = {conv}(result)')
    elif kind == 'json':
        lines.append('out.data = json.dumps(result, ensure_ascii=False)')
    elif kind == 'numbers':
        conv = 'float' if 'Float' in port.type else 'int'
        lines.append(f'out.data = [{conv}(x) for x in result]')
    elif kind == 'bytes':
        lines.append('out.data = list(bytes(result))')
    elif kind == 'image':
        lines.append('array_to_image(result, out, stamp)')
    elif kind == 'audio':
        samples = "np.asarray(result, dtype='<i2')"
        if port.type.endswith('/AudioDataStamped'):
            lines += ['out.header.stamp = stamp',
                      f'out.audio.data = list({samples}.tobytes())']
        elif port.type.endswith('/AudioData'):
            lines.append(f'out.data = list({samples}.tobytes())')
        else:
            lines.append(f'out.data = [int(x) for x in {samples}.reshape(-1)]')
    else:
        lines.append('set_message_fields(out, result)  # the dict keys are the message fields')
    return lines


def _periodic_args(spec: FunctionSpec, workspace: str) -> str:
    try:
        functions = list_functions(resolve_module(workspace, spec.module).file)
    except LauncherError:
        return ''
    info = next((f for f in functions if f['name'] == spec.function), None)
    return 'time.monotonic() - self.started' if info and info['params'] else ''


def generate(spec: FunctionSpec, workspace: str) -> str:
    inputs, output = resolve_ports(spec)
    resolved = resolve_module(workspace, spec.module)
    # scope B / C code is not in a ROS package: the steps name a placeholder package
    ros_package = resolved.package.ros_package or 'my_ros_package'
    types = sorted({p.type for p in [*inputs, output]})
    classes = class_names(types)
    kinds = {p.kind for p in [*inputs, output]}
    uses_numpy = bool(kinds & {'image', 'audio'})
    node_file = f'{spec.name}_node'
    imports = ['import sys', 'import traceback']
    if 'json' in kinds:
        imports.insert(0, 'import json')
    if spec.call == 'periodic':
        imports.append('import time')
    extra = []
    if uses_numpy:
        extra.append('import numpy as np')
    extra += ['import rclpy', 'from rclpy.node import Node',
              'from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy']
    if 'message' in kinds:
        extra.append('from rosidl_runtime_py import message_to_ordereddict, set_message_fields')
    extra += sorted(line for line, _ in classes.values())

    qos = spec.output.qos
    out_cls = classes[output.type][1]
    depends = ''.join(f' <exec_depend>{pkg}</exec_depend>'
                      for pkg in sorted({t.split('/')[0] for t in types}))
    head = f'''#!/usr/bin/env python3
{MARKER} {spec.id!r}.
# It does the same as the function node, as a plain rclpy node (no roshanavi needed):
#   {', '.join(p.topic for p in inputs) or 'a timer'} -> {spec.function}() -> {output.topic}
#
# How to keep it in your package ({ros_package}, ament_python):
#   1. Save it as {ros_package}/{resolved.package.top}/{node_file}.py
#   2. setup.py:  entry_points={{'console_scripts': [
#          '{node_file} = {resolved.package.top}.{node_file}:main']}}
#   3. package.xml:  <exec_depend>rclpy</exec_depend>{depends}
#   4. colcon build --packages-select {ros_package} && ros2 run {ros_package} {node_file}
# Or run this file directly in a sourced workspace: python3 {node_file}.py
"""{spec.name}: wraps {spec.module}.{spec.function} as a ROS 2 node."""

'''
    body = '\n'.join(imports) + '\n\n' + '\n'.join(extra) + '\n\n'
    body += (f'# Your function: a normal Python function that knows nothing about ROS.\n'
             f'from {spec.module} import {spec.function}\n')
    if 'image' in kinds:
        body += HELPERS_IMAGE
    body += '\n'
    for index, port in enumerate(inputs):
        expr, help_text = input_expr(port)
        body += (f'\ndef input_{index}(msg):\n'
                 f'    """{port.topic} ({port.type}) -> {help_text}."""\n'
                 f'    return {expr}\n\n')
    body += _node_class(spec, inputs, output, classes, out_cls, qos, workspace)
    body += f'''

def main(args=None):
    rclpy.init(args=args)
    node = {_class_name(spec)}()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


if __name__ == '__main__':
    sys.exit(main())
'''
    return head + body


def _class_name(spec: FunctionSpec) -> str:
    parts = [p for p in spec.name.split('_') if p]
    name = ''.join(p[:1].upper() + p[1:] for p in parts) or 'Function'
    return name + 'Node' if not name.endswith('Node') else name


def _node_class(spec: FunctionSpec, inputs: List[Port], output: Port,
                classes: Dict[str, Tuple[str, str]], out_cls: str, qos, workspace: str) -> str:
    rel = 'RELIABLE' if qos.reliability == 'reliable' else 'BEST_EFFORT'
    dur = 'TRANSIENT_LOCAL' if qos.durability == 'transient_local' else 'VOLATILE'
    lines = [f'class {_class_name(spec)}(Node):',
             f'    def __init__(self):',
             f'        super().__init__({spec.name!r})',
             f'        # Output: what the function returns is sent here.',
             f'        self.publisher = self.create_publisher(',
             f'            {out_cls}, {output.topic!r},',
             f'            QoSProfile(depth={qos.depth}, reliability=ReliabilityPolicy.{rel},',
             f'                       durability=DurabilityPolicy.{dur}))']
    in_qos = 'QoSProfile(depth=10, reliability=ReliabilityPolicy.BEST_EFFORT)'
    if spec.call == 'periodic':
        lines += ['        # No input: the function is called on a timer.',
                  '        self.started = time.monotonic()',
                  f'        self.create_timer({1.0 / float(spec.rate_hz):g}, self.on_timer)',
                  '',
                  '    def on_timer(self):',
                  f'        self.call_and_publish({_periodic_args(spec, workspace)})']
    elif spec.call == 'on_message':
        port = inputs[0]
        lines += ['        # Input: every message calls the function. Best effort accepts both',
                  '        # reliable and best-effort senders.',
                  f'        self.create_subscription({classes[port.type][1]}, {port.topic!r}, '
                  f'self.on_message, {in_qos})',
                  '',
                  '    def on_message(self, msg):',
                  '        self.call_and_publish(input_0(msg), stamp=stamp_of(msg))']
    else:
        trigger: Optional[int] = None if spec.trigger == 'any' else \
            [p.topic for p in inputs].index(spec.trigger)
        lines += ['        # Several inputs: keep the latest value of each; call when all have one.',
                  '        self.latest = {}']
        for index, port in enumerate(inputs):
            lines.append(f'        self.create_subscription({classes[port.type][1]}, '
                         f'{port.topic!r}, lambda msg: self.on_input({index}, input_{index}(msg), '
                         f'msg), {in_qos})')
        lines += ['',
                  '    def on_input(self, index, value, msg):',
                  '        self.latest[index] = value',
                  f'        if len(self.latest) < {len(inputs)}:',
                  '            return  # wait until every input has sent something']
        if trigger is not None:
            lines += [f'        if index != {trigger}:',
                      f'            return  # only {inputs[trigger].topic} triggers a call']
        lines.append(f'        self.call_and_publish(*[self.latest[i] for i in '
                     f'range({len(inputs)})], stamp=stamp_of(msg))')
    lines += ['',
              '    def call_and_publish(self, *args, stamp=None):',
              '        try:',
              f'            result = {spec.function}(*args)',
              '        except Exception:  # a bug in the function: log it, keep the node running',
              "            self.get_logger().error('the function failed:\\n' + traceback.format_exc())",
              '            return',
              '        if result is None:',
              '            return  # None means: send nothing this time',
              '        stamp = stamp or self.get_clock().now().to_msg()',
              *[f'        {line}' for line in output_lines(output, out_cls)],
              '        self.publisher.publish(out)']
    text = '\n'.join(lines) + '\n'
    return '''
def stamp_of(msg):
    """The input's header stamp if it has one (keeps latency measurable), else None."""
    header = getattr(msg, 'header', None)
    return header.stamp if header is not None else None


''' + text


def export_code(spec: FunctionSpec, workspace: str, directory: str) -> Dict[str, str]:
    """Write ``<directory>/<name>_node.py``; ``directory`` is already contained in the workspace.

    An existing file is replaced only when roshanavi generated it (never a user's file).
    """
    if has_control_chars(directory):
        raise LauncherError('invalid_request', 'directory must not contain control characters')
    # The node name becomes the file name and is written into the code: validate it again
    # (a spec loaded from a project file may be registered as invalid).
    command.validate_function(spec, workspace)
    source = generate(spec, workspace)
    return write_source(directory, f'{spec.name}_node.py', source)


def write_source(directory: str, filename: str, source: str) -> Dict[str, str]:
    """Check ``source`` with ``compile()`` and write ``<directory>/<filename>`` atomically.

    An existing file is replaced only when roshanavi generated it (never a user's file)."""
    compile(source, filename, 'exec')  # never write a file that does not parse
    path = os.path.join(directory, filename)
    try:
        os.makedirs(directory, exist_ok=True)
        if os.path.exists(path):
            with open(path, encoding='utf-8', errors='replace') as fh:
                if MARKER_PREFIX not in fh.read(4096):
                    raise LauncherError('file_exists', f'{path} exists and was not generated by '
                                        'roshanavi; choose another directory', 409)
        write_atomic(path, source)
    except OSError as exc:
        raise LauncherError('export_failed', f'cannot write {path}: {exc}', 500) from exc
    return {'file': path, 'command': f'python3 {path}'}
