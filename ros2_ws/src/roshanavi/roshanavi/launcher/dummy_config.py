"""Config files for persistent dummy / transform / function nodes and the launch-file export.

The dummy config is a small YAML document ``{dummy: <DummySpec>, data_dir: <path>}``
read by ``ros2 run roshanavi dummy --config <file>``; a transform node reads
``{transform: <TransformSpec>}`` (``ros2 run roshanavi transform --config <file>``);
a function node reads ``{function: <FunctionSpec>, workspace: <root>, status_file?}``.
Export writes one config per node plus a Python launch file that runs them all
without the roshanavi UI.
"""

import logging
import os
import tempfile
from typing import Any, Dict, List, Optional, Sequence

import yaml

from ..jobs import InjectSpec
from ..pydantic_compat import ValidationError, validation_errors
from .errors import LauncherError
from .schema import ClassSpec, DummySpec, FunctionSpec, TransformSpec, clean_dict

LOG = logging.getLogger(__name__)

CONFIG_HEADER = ('# roshanavi persistent dummy node config.\n'
                 '# Run: ros2 run roshanavi dummy --config <this file> '
                 '--ros-args -r __node:=<name>\n')
TRANSFORM_HEADER = ('# roshanavi transform node config.\n'
                    '# Run: ros2 run roshanavi transform --config <this file> '
                    '--ros-args -r __node:=<name>\n')
FUNCTION_HEADER = ('# roshanavi function node config.\n'
                   '# Run: ros2 run roshanavi function --config <this file> '
                   '--ros-args -r __node:=<name>\n')
CLASS_HEADER = ('# roshanavi class node config.\n'
                '# Run: ros2 run roshanavi function --config <this file> '
                '--ros-args -r __node:=<name>\n')
LAUNCH_FILE_NAME = 'roshanavi_dummies.launch.py'
LAUNCH_TEMPLATE = '''# Generated by roshanavi: persistent dummy (input), transform and function nodes.
#
# Run without the roshanavi server / web UI:
#     ros2 launch {launch_path!r}
# Requirement: the roshanavi package must still be installed and sourced,
# because each node runs `ros2 run roshanavi dummy|transform|function --config <yaml>`.
# The YAML files next to this launch file hold each node's settings.
import os

from launch import LaunchDescription
from launch_ros.actions import Node

HERE = os.path.dirname(os.path.abspath(__file__))


def generate_launch_description():
    return LaunchDescription([
{nodes}    ])
'''
NODE_TEMPLATE = '''        Node(
            package='roshanavi',
            executable={executable!r},
            name={name!r},
            namespace={namespace!r},
            output='screen',
            arguments=['--config', os.path.join(HERE, {config!r})],
        ),
'''


def write_atomic(path: str, text: str) -> None:
    """Write ``text`` to ``path`` via a temp file + rename in the same directory."""
    directory = os.path.dirname(path) or '.'
    fd, tmp = tempfile.mkstemp(prefix='.roshanavi-', dir=directory)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except OSError:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def config_text(spec: DummySpec, data_dir: str) -> str:
    body = {'dummy': clean_dict(spec), 'data_dir': os.path.realpath(data_dir)}
    return CONFIG_HEADER + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def transform_config_text(spec: TransformSpec) -> str:
    return TRANSFORM_HEADER + yaml.safe_dump({'transform': clean_dict(spec)}, sort_keys=False,
                                             allow_unicode=True)


def function_config_text(spec: FunctionSpec, workspace: str,
                         status_file: Optional[str] = None) -> str:
    body: Dict[str, Any] = {'function': clean_dict(spec),
                            'workspace': os.path.realpath(workspace)}
    if status_file:
        body['status_file'] = status_file
    return FUNCTION_HEADER + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def class_config_text(spec: ClassSpec, workspace: str, status_file: Optional[str] = None) -> str:
    body: Dict[str, Any] = {'class': clean_dict(spec), 'workspace': os.path.realpath(workspace)}
    if status_file:
        body['status_file'] = status_file
    return CLASS_HEADER + yaml.safe_dump(body, sort_keys=False, allow_unicode=True)


def load_function_config(path: str) -> Dict[str, Any]:
    """``{'spec': FunctionSpec | ClassSpec, 'workspace': str, 'status_file': str | None}``.

    ``ros2 run roshanavi function`` runs both: the key is ``function`` or ``class``."""
    raw = _read_yaml(path)
    key = 'class' if isinstance(raw, dict) and 'class' in raw else 'function'
    if not isinstance(raw, dict) or key not in raw or 'workspace' not in raw \
            or set(raw) - {key, 'workspace', 'status_file'}:
        raise LauncherError('invalid_config', f'{path}: expected keys "function" (or "class"), '
                            '"workspace" (and optionally "status_file")')
    try:
        spec = (ClassSpec if key == 'class' else FunctionSpec).model_validate(raw[key] or {})
    except ValidationError as exc:
        raise LauncherError('invalid_config', f'{path}: {format_errors(exc)}') from exc
    status = raw.get('status_file')
    return {'spec': spec, 'workspace': str(raw['workspace']),
            'status_file': str(status) if status else None}


def _read_yaml(path: str) -> Any:
    try:
        with open(path, encoding='utf-8') as fh:
            return yaml.safe_load(fh)
    except (OSError, yaml.YAMLError) as exc:
        raise LauncherError('invalid_config', f'cannot read {path}: {exc}') from exc


def load_transform_config(path: str) -> TransformSpec:
    raw = _read_yaml(path)
    if not isinstance(raw, dict) or set(raw) != {'transform'}:
        raise LauncherError('invalid_config', f'{path}: expected one key "transform"')
    try:
        return TransformSpec.model_validate(raw['transform'] or {})
    except ValidationError as exc:
        raise LauncherError('invalid_config', f'{path}: {format_errors(exc)}') from exc


def load_config(path: str) -> Dict[str, Any]:
    """``{'spec': DummySpec, 'data_dir': str}``; raises LauncherError on bad input."""
    raw = _read_yaml(path)
    if not isinstance(raw, dict) or set(raw) - {'dummy', 'data_dir'}:
        raise LauncherError('invalid_config', f'{path}: expected keys "dummy" and "data_dir"')
    try:
        spec = DummySpec.model_validate(raw.get('dummy') or {})
    except ValidationError as exc:
        raise LauncherError('invalid_config', f'{path}: {format_errors(exc)}') from exc
    return {'spec': spec, 'data_dir': str(raw.get('data_dir') or '/data')}


def format_errors(exc: ValidationError, prefix: str = '') -> str:
    parts = []
    for err in validation_errors(exc):
        loc = '.'.join(str(p) for p in (*([prefix] if prefix else []), *err['loc'])
                       if p != '__root__')
        parts.append(f'{loc or "(root)"}: {err["msg"]}')
    return '; '.join(parts)


def inject_spec(spec: DummySpec) -> InjectSpec:
    return InjectSpec(mode=spec.mode, topic=spec.topic, type=spec.type, payload=spec.payload,
                      rate_hz=spec.rate_hz, count=spec.count, source=spec.source,
                      loop=spec.loop, qos=spec.qos.model_dump(),
                      media=spec.media.model_dump() if spec.media else None)


def has_control_chars(text: str) -> bool:
    return any(ord(ch) < 32 or ord(ch) == 127 for ch in text)


def export(dummies: Sequence[DummySpec], directory: str, data_dir: str,
           transforms: Sequence[TransformSpec] = (), functions: Sequence[FunctionSpec] = (),
           workspace: str = '', classes: Sequence[ClassSpec] = ()) -> Dict[str, Any]:
    """Write ``<id>.yaml`` per dummy / transform / function / class and one launch file."""
    if not dummies and not transforms and not functions and not classes:
        raise LauncherError('invalid_request', 'there are no dummy, transform, function or '
                            'class nodes to export')
    if has_control_chars(directory):
        raise LauncherError('invalid_request', 'export directory must not contain control characters')
    items = [(spec, 'dummy', config_text(spec, data_dir)) for spec in dummies]
    items += [(spec, 'transform', transform_config_text(spec)) for spec in transforms]
    items += [(spec, 'function', function_config_text(spec, workspace)) for spec in functions]
    items += [(spec, 'function', class_config_text(spec, workspace)) for spec in classes]
    try:
        os.makedirs(directory, exist_ok=True)
        files: List[str] = []
        nodes = ''
        for spec, executable, text in items:
            config = f'{spec.id}.yaml'
            write_atomic(os.path.join(directory, config), text)
            files.append(os.path.join(directory, config))
            nodes += NODE_TEMPLATE.format(name=spec.name, namespace=spec.namespace or '',
                                          config=config, executable=executable)
        launch_path = os.path.join(directory, LAUNCH_FILE_NAME)
        write_atomic(launch_path, LAUNCH_TEMPLATE.format(launch_path=launch_path, nodes=nodes))
    except OSError as exc:
        raise LauncherError('export_failed', f'cannot write to {directory}: {exc}', 500) from exc
    LOG.info('exported %d node(s) to %s', len(items), directory)
    return {'directory': directory, 'launch_file': launch_path, 'files': [launch_path, *files],
            'command': f'ros2 launch {launch_path}'}
